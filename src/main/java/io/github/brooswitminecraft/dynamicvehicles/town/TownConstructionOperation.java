package io.github.brooswitminecraft.dynamicvehicles.town;

import net.minecraft.core.BlockPos;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;

import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;

/**
 * MINECRAFT-454 [coordinator design 51327, stage 2 - bounded block/resource integration]: one
 * durable, immutable-identity construction operation record - the "intent" row the stage 2
 * contract requires exist in {@code TownStorage} BEFORE any world effect, and the sole recovery
 * entry point afterward (never a surviving campfire - see {@link TownStorage#pendingConstructionOperations}).
 *
 * <p>{@code operationId} is minted ONCE, by the caller, before this record is ever created (see
 * {@link TownStorage#reserveConstructionOperation}), and is never regenerated by a retry - a
 * second reservation call with the SAME id and the SAME content is always idempotent (returns the
 * existing record, changes nothing); one with the SAME id but DIFFERENT content is REJECTED
 * outright (see {@link #sameContentAs}), never silently treated as the unrelated old operation
 * (coordinator review 51330). {@code operationId} is also the SAME id {@link
 * TownStorageChunkCheckpoint}'s operation-aware overload uses as its witness, so a chunk's own disk
 * snapshot can be linked back to this exact operation after a restart.
 *
 * <p>[coordinator review 51330] {@code effects} is the exact, immutable before/after record this
 * stage's contract requires - NOT merely an opaque paid-progress signature, which cannot by itself
 * reconstruct removed natural terrain, verify exact before-vs-after states, restore required
 * block-entity data, or recover a disappeared plan/anchor. {@code affectedChunks()} is DERIVED from
 * these effects' own positions, never supplied independently, so chunk enumeration for recovery can
 * never drift from what was actually recorded.
 *
 * <p>{@code reservedCost} is escrow: subtracted from the town's ordinary spendable balance at
 * reservation time (see {@link TownStorage#reserveConstructionOperation}), restored exactly once
 * on {@link TownStorage#cancelConstructionOperation}, and never touched again at {@link
 * TownStorage#settleConstructionOperation} - settlement only ever records that this already-paid
 * operation's effects are durably committed, it never debits a second time.
 */
record TownConstructionOperation(
        UUID operationId,
        ResourceKey<Level> dimension,
        String townKey,
        String siteOwner,
        UUID anchorGenerationToken,
        UUID builderId,
        Optional<UUID> beneficiaryId,
        List<CellEffect> effects,
        Map<TownResourceCategory, Integer> reservedCost,
        Phase phase) {

    /** [coordinator review 51330] One cell's exact before/after effect. {@code signature} retains
     *  the SAME opaque expected-block/cost/template identity {@link TownStorage}'s own
     *  {@code PlacedCell} already uses for ordinary paid-progress - kept here purely for continuity
     *  with that existing concept, and never treated as a substitute for the exact {@code before}/
     *  {@code after} states and block-entity payloads this record actually carries. */
    record CellEffect(BlockPos pos, BlockState before, BlockState after,
                       BlockEntitySnapshot beforeBlockEntity, BlockEntitySnapshot afterBlockEntity,
                       String signature) {
        /** [coordinator review 51335] {@code pos} is frozen to an immutable snapshot here - a
         *  caller handing in a {@code BlockPos.MutableBlockPos} (e.g. a reused cursor from a
         *  construction loop) must never be able to alter this record's own identity, {@link
         *  #sameContentAs}, or {@link #affectedChunks()} after the fact just by continuing to move
         *  that same instance. {@link BlockPos#immutable()} is a no-op copy for an already-immutable
         *  {@code BlockPos}, matching the exact pattern {@code TownStorage#bindDonationBox} already
         *  uses for the same reason. */
        CellEffect {
            Objects.requireNonNull(pos, "pos");
            Objects.requireNonNull(before, "before");
            Objects.requireNonNull(after, "after");
            Objects.requireNonNull(beforeBlockEntity, "beforeBlockEntity");
            Objects.requireNonNull(afterBlockEntity, "afterBlockEntity");
            Objects.requireNonNull(signature, "signature");
            pos = pos.immutable();
        }
    }

    /** [coordinator review 51330] Exactly one of: no block-entity at this position/time, its exact
     *  captured NBT, or an EXPLICIT refusal to represent an unsupported block-entity type. A
     *  block-entity this mod cannot faithfully snapshot is never silently represented as
     *  {@link None} - that would read to recovery as proof there never was one, when the real
     *  answer is "this record cannot prove what was there." */
    sealed interface BlockEntitySnapshot {
        record None() implements BlockEntitySnapshot {}

        /** [coordinator review 51335] {@code CompoundTag} is mutable - a caller handing in a live
         *  reference (or holding onto one returned by {@link #nbt()}) must never be able to alter
         *  this operation's own durable before/after evidence after the fact just by mutating that
         *  tag later. Defensively snapshot on BOTH construction AND every access: {@link #nbt()} is
         *  explicitly overridden to return a fresh {@link CompoundTag#copy()} every time, never the
         *  internally-stored instance, exactly as {@link TownStorageChunkCheckpoint} and {@link
         *  TownStorageDurableWriter}'s own callers already copy before handing a tag across a
         *  trust boundary. */
        record Captured(CompoundTag nbt) implements BlockEntitySnapshot {
            public Captured {
                Objects.requireNonNull(nbt, "nbt");
                nbt = nbt.copy();
            }

            @Override
            public CompoundTag nbt() {
                return nbt.copy();
            }
        }

        record Unsupported(String blockEntityType) implements BlockEntitySnapshot {}
    }

    /** [coordinator design 51327] "Separate two outcomes: BLOCK_RESOURCE_SETTLED and
     *  HANDOFF_READY. Neither implies the other." This enum is scoped to the FIRST outcome only -
     *  the block/resource effects and their escrow. Final beneficiary handoff readiness is tracked
     *  entirely separately (see {@code TownConstructionOperationService}'s own reconciliation),
     *  never folded into this phase. */
    enum Phase {
        /** Intent persisted, escrow reserved, no world effects attempted yet. */
        RESERVED,
        /** World effects applied and chunk-checkpointed with this operation's own witness, but
         *  settlement (paid-progress + balance-delta acknowledgment) not yet recorded. */
        WORLD_APPLIED,
        /** Terminal: settlement acknowledged. Escrow was already spent at reservation; nothing
         *  further changes the balance. */
        SETTLED,
        /** Terminal: cancelled before settlement: escrow was refunded exactly once. */
        CANCELLED
    }

    TownConstructionOperation {
        effects = List.copyOf(effects);
        reservedCost = Map.copyOf(reservedCost);
        if (effects.isEmpty()) {
            throw new IllegalArgumentException("a construction operation must record at least one cell effect");
        }
        Set<BlockPos> seenPositions = new HashSet<>();
        for (CellEffect effect : effects) {
            if (!seenPositions.add(effect.pos())) {
                throw new IllegalArgumentException("a construction operation cannot record two effects at the same position");
            }
        }
        for (int amount : reservedCost.values()) {
            if (amount < 0) {
                throw new IllegalArgumentException("reserved cost must be >= 0: " + amount);
            }
        }
    }

    /** [coordinator review 51330] Derived from the actual recorded effects, never supplied
     *  independently - the exact set of chunks this operation's witness-linked checkpoint (see
     *  {@link TownStorageChunkCheckpoint}) must cover. */
    Set<ChunkPos> affectedChunks() {
        Set<ChunkPos> chunks = new HashSet<>();
        for (CellEffect effect : effects) {
            chunks.add(new ChunkPos(effect.pos()));
        }
        return Set.copyOf(chunks);
    }

    boolean isTerminal() {
        return phase == Phase.SETTLED || phase == Phase.CANCELLED;
    }

    /** {@code true} while this operation still fences its own site - i.e. it has neither settled
     *  nor been cancelled yet. See {@link TownStorage#isSiteFencedByUnsettledOperation}. */
    boolean isUnsettled() {
        return phase == Phase.RESERVED || phase == Phase.WORLD_APPLIED;
    }

    TownConstructionOperation withPhase(Phase newPhase) {
        return new TownConstructionOperation(operationId, dimension, townKey, siteOwner, anchorGenerationToken,
                builderId, beneficiaryId, effects, reservedCost, newPhase);
    }

    /** [coordinator review 51330] "Reject duplicate-ID requests with different contents rather
     *  than returning an unrelated old operation." Compares every identity/content field EXCEPT
     *  {@code phase}, which legitimately advances between an original reservation and a later
     *  idempotent replay of that same request. */
    boolean sameContentAs(TownConstructionOperation other) {
        return operationId.equals(other.operationId) && dimension.equals(other.dimension)
                && townKey.equals(other.townKey) && siteOwner.equals(other.siteOwner)
                && anchorGenerationToken.equals(other.anchorGenerationToken) && builderId.equals(other.builderId)
                && beneficiaryId.equals(other.beneficiaryId) && effects.equals(other.effects)
                && reservedCost.equals(other.reservedCost);
    }
}
